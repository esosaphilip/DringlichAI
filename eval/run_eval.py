"""End-to-end evaluation harness for DringlichAI's triage pipeline.

WHY THIS EXISTS: the README claims the system triages correctly, but a claim without a measured
number is just marketing. This harness runs the REAL pipeline (retrieval + Mistral, no mocks)
over the fixed golden set and reports exact-match accuracy, per-class precision/recall, and —
separately and with zero tolerance — any case where a true P1 was under-triaged. It also runs
one deliberately unmatched case to document the current fallback behaviour instead of scoring it.

INTERVIEW TALKING POINT: aggregate accuracy flatters a triage system; a model that is 90% right
overall but habitually downgrades P1 is dangerous, so P1 under-triage is its own hard-fail metric
rather than being averaged away. An optional retrieval diagnostic further separates "the rule was
never retrieved" from "the model misread the rule it was given" — two different problems with
two different fixes.

Run from the repo root with Ollama running locally:
    python eval/run_eval.py
Outputs a results table to stdout and writes the same to eval/results.md.
"""

import os
import sys
import uuid
from collections import defaultdict

# --- Make the harness runnable both as `python eval/run_eval.py` and `python -m eval.run_eval` ---
# The script dir must be on the path for `golden_set`, and the repo root for `priority_analyzer_agent`.
_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.dirname(_THIS_DIR)
for _p in (_THIS_DIR, _REPO_ROOT):
    if _p not in sys.path:
        sys.path.insert(0, _p)

from golden_set import GOLDEN_SET, NO_MATCH_CASE  # noqa: E402
from priority_analyzer_agent import graph, vector_store  # noqa: E402

RESULTS_PATH = os.path.join(_THIS_DIR, "results.md")
ALL_CLASSES = [1, 2, 3, 4, 5]


def run_case(case):
    """Runs one case through the real graph and returns (predicted_priority, retrieval_hit, values).

    A fresh, unique thread_id per case is essential: the MemorySaver checkpointer is a
    module-level singleton, so reusing a thread_id would leak state between cases and silently
    poison the measurement.
    """
    thread_id = f"eval-{case['id']}-{uuid.uuid4().hex}"
    config = {"configurable": {"thread_id": thread_id}}
    initial_state = {
        "patient_name": f"Eval {case['id']}",
        "sickness": case["symptoms"],
        "priority": 0,
        "doctor_name": "Eval",
        "status": "eval",
        "appointment_time": "00:00",
    }
    graph.invoke(initial_state, config)
    values = graph.get_state(config).values
    predicted = values.get("priority")

    # OPTIONAL (stretch) diagnostic: was the matching rule even in the top-2 chunks the model saw?
    # This repeats the same similarity_search the node performs, so it reflects the model's actual
    # context. Only meaningful for cases that have a known guideline id.
    retrieval_hit = None
    if case.get("guideline"):
        docs = vector_store.similarity_search(case["symptoms"], k=2)
        joined = "\n".join(d.page_content for d in docs)
        retrieval_hit = case["guideline"] in joined

    return predicted, retrieval_hit, values


def _fmt(value, digits=2):
    return "n/a" if value is None else f"{value:.{digits}f}"


def compute_metrics(rows):
    """Pure aggregation over the per-case rows — kept separate so the numbers are auditable."""
    total = len(rows)
    correct = sum(1 for r in rows if r["predicted"] == r["expected"])

    # Per-class precision/recall: an aggregate accuracy hides the class we care about most.
    per_class = {}
    for cls in ALL_CLASSES:
        predicted_pos = [r for r in rows if r["predicted"] == cls]
        actual_pos = [r for r in rows if r["expected"] == cls]
        tp = sum(1 for r in rows if r["predicted"] == cls and r["expected"] == cls)
        per_class[cls] = {
            "support": len(actual_pos),
            "precision": (tp / len(predicted_pos)) if predicted_pos else None,
            "recall": (tp / len(actual_pos)) if actual_pos else None,
        }

    # Zero-tolerance safety check: a true P1 answered as 2-5 is a hard failure on its own.
    under_triage = [r for r in rows if r["expected"] == 1 and r["predicted"] != 1]

    return {
        "total": total,
        "correct": correct,
        "accuracy": correct / total if total else 0.0,
        "per_class": per_class,
        "under_triage": under_triage,
    }


def build_markdown(rows, metrics, no_match_result):
    lines = []
    lines.append("# DringlichAI — triage evaluation results\n")
    lines.append("Generated by `eval/run_eval.py` against the real pipeline "
                 "(retrieval + `mistral:latest`, no mocks).\n")
    lines.append("## Per-case results\n")
    lines.append("| ID | Expected | Predicted | Match | Guideline | Rule in top-2 chunks |")
    lines.append("|---|---|---|---|---|---|")
    for r in rows:
        hit = "—" if r["retrieval_hit"] is None else ("yes" if r["retrieval_hit"] else "no")
        lines.append(
            f"| {r['id']} | P{r['expected']} | P{r['predicted']} | "
            f"{'✅' if r['predicted'] == r['expected'] else '❌'} | {r['guideline']} | {hit} |"
        )
    lines.append("")

    lines.append("## Metrics\n")
    lines.append(f"- **Overall exact-match accuracy: {metrics['correct']}/{metrics['total']} "
                 f"= {metrics['accuracy'] * 100:.1f}%**")
    lines.append("")

    lines.append("### Per-class precision / recall\n")
    lines.append("| Class | Support | Precision | Recall |")
    lines.append("|---|---|---|---|")
    for cls in ALL_CLASSES:
        pc = metrics["per_class"][cls]
        lines.append(f"| P{cls} | {pc['support']} | {_fmt(pc['precision'])} | {_fmt(pc['recall'])} |")
    lines.append("")

    lines.append("### Safety check — P1 under-triage (zero tolerance)\n")
    if metrics["under_triage"]:
        lines.append(f"**FAIL — {len(metrics['under_triage'])} true P1 case(s) were downgraded:**\n")
        for r in metrics["under_triage"]:
            lines.append(f"- {r['id']}: expected P1, predicted P{r['predicted']} — {r['note']}")
    else:
        lines.append("**PASS — no true P1 case was under-triaged (0 hard failures).**")
    lines.append("")

    lines.append("### No-match case (documented, not scored)\n")
    lines.append(f"- `{no_match_result['id']}` received priority **P{no_match_result['predicted']}**. "
                 "This case has no clean guideline match by design, so it is documented rather than "
                 "scored right/wrong. The pipeline's priority-3 default only kicks in when the model "
                 "returns *unparseable* output; when the model still returns a parseable (if unmapped) "
                 "answer, that value is used — which is what happened here. The observation is "
                 "recorded either way.")
    lines.append("")

    hit_rows = [r for r in rows if r["retrieval_hit"] is not None]
    if hit_rows:
        hits = sum(1 for r in hit_rows if r["retrieval_hit"])
        lines.append("### Optional retrieval diagnostic (stretch)\n")
        lines.append(f"- The matching rule ID appeared in the retrieved top-2 chunks for "
                     f"**{hits}/{len(hit_rows)}** cases. Where it did not, a wrong answer points at "
                     "retrieval missing the rule rather than the model misreading it — a different "
                     "problem with a different fix.")
        lines.append("")
    return "\n".join(lines)


def print_table(rows, metrics, no_match_result):
    print("\n" + "=" * 78)
    print("DringlichAI triage evaluation — per-case results")
    print("=" * 78)
    print(f"{'ID':<12}{'Exp':<6}{'Pred':<6}{'Match':<7}{'Guideline':<11}{'Retr':<6}")
    print("-" * 78)
    for r in rows:
        hit = "—" if r["retrieval_hit"] is None else ("yes" if r["retrieval_hit"] else "no")
        print(f"{r['id']:<12}P{r['expected']:<5}P{r['predicted']:<5}"
              f"{('OK' if r['predicted'] == r['expected'] else 'MISS'):<7}{str(r['guideline']):<11}{hit:<6}")

    print("-" * 78)
    print(f"Overall exact-match accuracy: {metrics['correct']}/{metrics['total']} "
          f"= {metrics['accuracy'] * 100:.1f}%")

    print("\nPer-class precision / recall:")
    print(f"{'Class':<8}{'Support':<9}{'Precision':<11}{'Recall':<8}")
    for cls in ALL_CLASSES:
        pc = metrics["per_class"][cls]
        print(f"P{cls:<7}{pc['support']:<9}{_fmt(pc['precision']):<11}{_fmt(pc['recall']):<8}")

    print("\nSAFETY CHECK — P1 under-triage (expected P1 predicted as P2-P5, zero tolerance):")
    if metrics["under_triage"]:
        print(f"  FAIL — {len(metrics['under_triage'])} hard failure(s):")
        for r in metrics["under_triage"]:
            print(f"    - {r['id']}: expected P1, predicted P{r['predicted']} ({r['note']})")
    else:
        print("  PASS — no true P1 case was under-triaged.")

    print("\nNO-MATCH CASE (documented, not scored):")
    print(f"  {no_match_result['id']} -> predicted P{no_match_result['predicted']}")
    print("  This input has no clean guideline match by design; the priority it received is")
    print("  recorded as an observation, not scored right or wrong.")

    hit_rows = [r for r in rows if r["retrieval_hit"] is not None]
    if hit_rows:
        hits = sum(1 for r in hit_rows if r["retrieval_hit"])
        print("\nOPTIONAL retrieval diagnostic (stretch): the matching rule ID was in the top-2")
        print(f"  retrieved chunks for {hits}/{len(hit_rows)} cases.")
    print("=" * 78 + "\n")


def main():
    print("Running DringlichAI evaluation against the real pipeline "
          "(Ollama must be running)...")
    rows = []
    try:
        for case in GOLDEN_SET:
            print(f"  [{case['id']}] triaging...")
            predicted, retrieval_hit, _ = run_case(case)
            rows.append({
                "id": case["id"],
                "expected": case["expected_priority"],
                "predicted": predicted,
                "guideline": case["guideline"],
                "note": case["note"],
                "retrieval_hit": retrieval_hit,
            })

        print(f"  [{NO_MATCH_CASE['id']}] triaging (no-match case)...")
        no_match_predicted, _, _ = run_case(NO_MATCH_CASE)
        no_match_result = {"id": NO_MATCH_CASE["id"], "predicted": no_match_predicted}
    except Exception as exc:  # noqa: BLE001 - surface the real failure, don't fake numbers
        print(f"\nERROR: evaluation could not complete — is Ollama running with "
              f"'mistral:latest' and 'nomic-embed-text:latest' pulled?\n  {type(exc).__name__}: {exc}")
        sys.exit(1)

    metrics = compute_metrics(rows)
    print_table(rows, metrics, no_match_result)

    markdown = build_markdown(rows, metrics, no_match_result)
    with open(RESULTS_PATH, "w", encoding="utf-8") as fh:
        fh.write(markdown)
    print(f"Wrote {RESULTS_PATH}")


if __name__ == "__main__":
    main()
